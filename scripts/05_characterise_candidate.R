get_omics_features <- function(x_train, prefixes = omics_prefixes) {
  colnames(x_train)[
    str_detect(
      colnames(x_train),
      paste0("^(", paste(prefixes, collapse = "|"), ")")
    )
  ]
}

get_clinical_features <- function(x_train, prefixes = omics_prefixes) {
  colnames(x_train)[
    !str_detect(
      colnames(x_train),
      paste0("^(", paste(prefixes, collapse = "|"), ")")
    )
  ]
}

select_auc_features <- function(
  x_train,
  y_train,
  top_k,
  prefixes = omics_prefixes
) {
  omics_cols <- get_omics_features(
    x_train,
    prefixes
  )

  if (length(omics_cols) == 0 || is.na(top_k)) {
    return(character())
  }

  auc_table <- map_dfr(
    omics_cols,
    function(feature_name) {
      feature_values <- x_train[, feature_name]

      if (
        length(
          unique(feature_values[!is.na(feature_values)])
        ) < 2
      ) {
        return(
          tibble(
            feature = feature_name,
            auc_value = NA_real_,
            auc_strength = NA_real_
          )
        )
      }

      auc_value <- tryCatch(
        as.numeric(
          pROC::auc(
            pROC::roc(
              response = y_train,
              predictor = feature_values,
              quiet = TRUE
            )
          )
        ),
        error = function(e) NA_real_
      )

      tibble(
        feature = feature_name,
        auc_value = auc_value,
        auc_strength = ifelse(
          is.na(auc_value),
          NA_real_,
          max(auc_value, 1 - auc_value)
        )
      )
    }
  )

  auc_table %>%
    filter(!is.na(auc_strength)) %>%
    arrange(desc(auc_strength)) %>%
    slice_head(n = min(top_k, nrow(.))) %>%
    pull(feature)
}

prep_train_test <- function(train_df, test_df) {
  y_train <- train_df$outcome
  y_test <- test_df$outcome

  x_train_raw <- train_df %>%
    select(-outcome)

  x_test_raw <- test_df %>%
    select(-outcome)

  numeric_vars <- names(x_train_raw)[
    map_lgl(x_train_raw, is.numeric)
  ]

  categorical_vars <- setdiff(
    names(x_train_raw),
    numeric_vars
  )

  # Numeric preprocessing
  if (length(numeric_vars) > 0) {
    x_train_num <- x_train_raw %>%
      select(all_of(numeric_vars))

    x_test_num <- x_test_raw %>%
      select(all_of(numeric_vars))

    train_medians <- apply(
      x_train_num,
      2,
      median,
      na.rm = TRUE
    )

    train_medians[is.na(train_medians)] <- 0

    for (variable_name in numeric_vars) {
      x_train_num[[variable_name]][
        is.na(x_train_num[[variable_name]])
      ] <- train_medians[[variable_name]]

      x_test_num[[variable_name]][
        is.na(x_test_num[[variable_name]])
      ] <- train_medians[[variable_name]]
    }
  } else {
    x_train_num <- tibble(
      .rows = nrow(x_train_raw)
    )

    x_test_num <- tibble(
      .rows = nrow(x_test_raw)
    )
  }

  # Categorical preprocessing
  if (length(categorical_vars) > 0) {
    x_train_cat <- x_train_raw %>%
      select(all_of(categorical_vars)) %>%
      mutate(
        across(
          everything(),
          ~ replace_na(as.character(.x), "Missing")
        )
      )

    x_test_cat <- x_test_raw %>%
      select(all_of(categorical_vars)) %>%
      mutate(
        across(
          everything(),
          ~ replace_na(as.character(.x), "Missing")
        )
      )

    for (variable_name in categorical_vars) {
      train_levels <- unique(
        c(
          x_train_cat[[variable_name]],
          "Other"
        )
      )

      x_test_cat[[variable_name]][
        !x_test_cat[[variable_name]] %in% train_levels
      ] <- "Other"

      x_train_cat[[variable_name]] <- factor(
        x_train_cat[[variable_name]],
        levels = train_levels
      )

      x_test_cat[[variable_name]] <- factor(
        x_test_cat[[variable_name]],
        levels = train_levels
      )
    }

    x_train_cat <- model.matrix(
      ~ . - 1,
      data = x_train_cat
    ) %>%
      as.data.frame(
        check.names = FALSE
      )

    x_test_cat <- model.matrix(
      ~ . - 1,
      data = x_test_cat
    ) %>%
      as.data.frame(
        check.names = FALSE
      )

    missing_test_columns <- setdiff(
      names(x_train_cat),
      names(x_test_cat)
    )

    extra_test_columns <- setdiff(
      names(x_test_cat),
      names(x_train_cat)
    )

    for (missing_column in missing_test_columns) {
      x_test_cat[[missing_column]] <- 0
    }

    if (length(extra_test_columns) > 0) {
      x_test_cat <- x_test_cat %>%
        select(-all_of(extra_test_columns))
    }

    x_test_cat <- x_test_cat[
      ,
      names(x_train_cat),
      drop = FALSE
    ]
  } else {
    x_train_cat <- tibble(
      .rows = nrow(x_train_raw)
    )

    x_test_cat <- tibble(
      .rows = nrow(x_test_raw)
    )
  }

  x_train <- bind_cols(
    x_train_num,
    x_train_cat
  )

  x_test <- bind_cols(
    x_test_num,
    x_test_cat
  )

  train_standard_deviations <- apply(
    x_train,
    2,
    sd,
    na.rm = TRUE
  )

  keep_variables <- names(
    train_standard_deviations
  )[
    is.finite(train_standard_deviations) &
      train_standard_deviations > 0
  ]

  x_train <- x_train[
    ,
    keep_variables,
    drop = FALSE
  ]

  x_test <- x_test[
    ,
    keep_variables,
    drop = FALSE
  ]

  train_means <- colMeans(x_train)
  train_standard_deviations <- apply(
    x_train,
    2,
    sd
  )

  list(
    x_train = as.matrix(
      scale(
        x_train,
        center = train_means,
        scale = train_standard_deviations
      )
    ),
    x_test = as.matrix(
      scale(
        x_test,
        center = train_means,
        scale = train_standard_deviations
      )
    ),
    y_train = y_train,
    y_test = y_test,
    feature_names = keep_variables
  )
}

