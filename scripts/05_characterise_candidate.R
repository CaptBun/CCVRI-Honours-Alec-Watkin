# General helpers
calc_auprc <- function(y_true, pred) {
  if (length(unique(y_true)) < 2) {
    return(NA_real_)
  }

  tryCatch(
    PRROC::pr.curve(
      scores.class0 = pred[y_true == 1],
      scores.class1 = pred[y_true == 0],
      curve = FALSE
    )$auc.integral,
    error = function(e) NA_real_
  )
}

calc_calibration <- function(y_true, pred) {
  pred_clipped <- pmin(pmax(pred, 1e-6), 1 - 1e-6)
  logit_pred <- qlogis(pred_clipped)

  calibration_fit <- tryCatch(
    glm(y_true ~ logit_pred, family = binomial),
    error = function(e) NULL
  )

  if (is.null(calibration_fit)) {
    return(
      tibble(
        calibration_intercept = NA_real_,
        calibration_slope = NA_real_,
        brier_score = mean((y_true - pred)^2, na.rm = TRUE)
      )
    )
  }

  tibble(
    calibration_intercept = as.numeric(coef(calibration_fit)[1]),
    calibration_slope = as.numeric(coef(calibration_fit)[2]),
    brier_score = mean((y_true - pred)^2, na.rm = TRUE)
  )
}

calc_threshold_metrics <- function(y_true, pred) {
  roc_obj <- pROC::roc(
    response = y_true,
    predictor = pred,
    direction = "<",
    quiet = TRUE
  )

  best <- pROC::coords(
    roc_obj,
    x = "best",
    best.method = "youden",
    ret = c(
      "threshold",
      "sensitivity",
      "specificity",
      "ppv",
      "npv"
    ),
    transpose = FALSE
  )

  predicted_class <- ifelse(pred >= best$threshold, 1, 0)

  tibble(
    threshold = as.numeric(best$threshold),
    sensitivity = as.numeric(best$sensitivity),
    specificity = as.numeric(best$specificity),
    ppv = as.numeric(best$ppv),
    npv = as.numeric(best$npv),
    youden_j = as.numeric(best$sensitivity + best$specificity - 1),
    accuracy = mean(predicted_class == y_true, na.rm = TRUE),
    balanced_accuracy = mean(
      c(best$sensitivity, best$specificity),
      na.rm = TRUE
    ),
    true_positive = sum(
      predicted_class == 1 & y_true == 1,
      na.rm = TRUE
    ),
    false_positive = sum(
      predicted_class == 1 & y_true == 0,
      na.rm = TRUE
    ),
    true_negative = sum(
      predicted_class == 0 & y_true == 0,
      na.rm = TRUE
    ),
    false_negative = sum(
      predicted_class == 0 & y_true == 1,
      na.rm = TRUE
    )
  )
}

make_weights <- function(y) {
  n_pos <- sum(y == 1, na.rm = TRUE)
  n_neg <- sum(y == 0, na.rm = TRUE)

  if (n_pos == 0 || n_neg == 0) {
    return(rep(1, length(y)))
  }

  ifelse(y == 1, n_neg / n_pos, 1)
}

classify_feature_modality <- function(feature_name) {
  case_when(
    str_starts(feature_name, "lipo_") ~ "Lipoproteins",
    str_starts(feature_name, "lipid_") ~ "Lipids",
    str_starts(feature_name, "sm_") ~ "Small molecules",
    str_starts(feature_name, "path_") ~ "Pathology",
    TRUE ~ "Expanded clinical"
  )
}

clean_feature_label <- function(feature_name) {
  feature_name %>%
    str_remove("^lipo_") %>%
    str_remove("^lipid_") %>%
    str_remove("^sm_") %>%
    str_remove("^path_") %>%
    str_replace_all("\\.", " ") %>%
    str_squish()
}

mode_value <- function(x) {
  valid_x <- x[!is.na(x)]

  if (length(valid_x) == 0) {
    return(NA)
  }

  names(sort(table(valid_x), decreasing = TRUE))[1]
}

