pr_curve_data <- map_dfr(
  pr_thresholds,
  function(current_threshold) {
    predicted_class <- ifelse(
      candidate_predictions$pred >= current_threshold,
      1,
      0
    )

    true_positive <- sum(
      predicted_class == 1 &
        candidate_predictions$outcome == 1
    )

    false_positive <- sum(
      predicted_class == 1 &
        candidate_predictions$outcome == 0
    )

    false_negative <- sum(
      predicted_class == 0 &
        candidate_predictions$outcome == 1
    )

    tibble(
      threshold = current_threshold,
      precision = ifelse(
        true_positive + false_positive == 0,
        NA_real_,
        true_positive /
          (true_positive + false_positive)
      ),
      recall = ifelse(
        true_positive + false_negative == 0,
        NA_real_,
        true_positive /
          (true_positive + false_negative)
      )
    )
  }
) %>%
  filter(
    !is.na(precision),
    !is.na(recall)
  )

