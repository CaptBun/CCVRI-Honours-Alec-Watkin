#
# Five approximately equal-sized groups are used rather than deciles because
# the cohort contains relatively few MACE events. Exact binomial confidence
# intervals are shown to make the sampling uncertainty within each group clear.
# The points are deliberately not connected: each group is an independent
# summary rather than a continuous observed trajectory.
calibration_data <- candidate_predictions %>%
  mutate(
    calibration_group = ntile(
      pred,
      calibration_groups
    )
  ) %>%
  group_by(calibration_group) %>%
  summarise(
    n = n(),
    mean_predicted_score = mean(pred),
    median_predicted_score = median(pred),
    min_predicted_score = min(pred),
    max_predicted_score = max(pred),
    observed_mace_n = sum(outcome == 1),
    observed_mace_rate = mean(outcome == 1),
    .groups = "drop"
  ) %>%
  mutate(
    ci_low = case_when(
      observed_mace_n == 0 ~ 0,
      TRUE ~ qbeta(
        0.025,
        observed_mace_n,
        n - observed_mace_n + 1
      )
    ),
    ci_high = case_when(
      observed_mace_n == n ~ 1,
      TRUE ~ qbeta(
        0.975,
        observed_mace_n + 1,
        n - observed_mace_n
      )
    ),
    group_label = paste0(
      observed_mace_n,
      "/",
      n
    )
  )

