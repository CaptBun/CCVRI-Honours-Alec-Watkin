# Confusion matrix
candidate_threshold <- candidate_performance_summary$threshold

confusion_data <- candidate_predictions %>%
  mutate(
    observed = if_else(
      outcome == 1,
      "MACE",
      "No MACE"
    ),
    predicted = if_else(
      pred >= candidate_threshold,
      "MACE",
      "No MACE"
    ),
    cell = case_when(
      observed == "No MACE" &
        predicted == "No MACE" ~ "TN",
      observed == "No MACE" &
        predicted == "MACE" ~ "FP",
      observed == "MACE" &
        predicted == "No MACE" ~ "FN",
      observed == "MACE" &
        predicted == "MACE" ~ "TP"
    )
  ) %>%
  count(
    observed,
    predicted,
    cell
  ) %>%
  complete(
    observed = c(
      "No MACE",
      "MACE"
    ),
    predicted = c(
      "No MACE",
      "MACE"
    ),
    fill = list(n = 0)
  ) %>%
  mutate(
    cell = case_when(
      observed == "No MACE" &
        predicted == "No MACE" ~ "TN",
      observed == "No MACE" &
        predicted == "MACE" ~ "FP",
      observed == "MACE" &
        predicted == "No MACE" ~ "FN",
      observed == "MACE" &
        predicted == "MACE" ~ "TP"
    )
  ) %>%
  group_by(observed) %>%
  mutate(
    row_total = sum(n),
    row_percent = n / row_total
  ) %>%
  ungroup() %>%
  mutate(
    classification = if_else(
      cell %in% c("TN", "TP"),
      "Correct",
      "Incorrect"
    ),
    observed = factor(
      observed,
      levels = c(
        "MACE",
        "No MACE"
      )
    ),
    predicted = factor(
      predicted,
      levels = c(
        "No MACE",
        "MACE"
      )
    ),
    label = paste0(
      cell,
      "\n",
      n,
      "\n(",
      sprintf("%.1f", 100 * row_percent),
      "%)"
    )
  )

