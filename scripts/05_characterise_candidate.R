# Optional SHAP analysis
if (run_shap) {
  if (!requireNamespace("fastshap", quietly = TRUE)) {
    warning(
      paste0(
        "Package 'fastshap' is not installed. ",
        "Skipping SHAP analysis. Install with ",
        "install.packages('fastshap') and rerun."
      )
    )
  } else {
    set.seed(shap_seed)

    shap_x <- as.data.frame(
      refit_x
    )

    prediction_wrapper <- function(object, newdata) {
      as.numeric(
        predict(
          object,
          newx = as.matrix(newdata),
          type = "response"
        )
      )
    }

    shap_values <- fastshap::explain(
      object = refit_model,
      X = shap_x,
      pred_wrapper = prediction_wrapper,
      nsim = shap_nsim,
      adjust = TRUE,
      .parallel = FALSE
    )

    shap_values <- as.data.frame(
      shap_values
    )

    save_table(
      shap_values %>%
        mutate(
          patient_index = row_number(),
          .before = 1
        ),
      "05N_candidate_shap_values.csv"
    )

    shap_importance <- tibble(
      feature = names(shap_values),
      mean_abs_shap = map_dbl(
        shap_values,
        ~ mean(abs(.x), na.rm = TRUE)
      )
    ) %>%
      mutate(
        feature_label =
          clean_feature_label(feature),
        feature_modality =
          classify_feature_modality(feature)
      ) %>%
      arrange(
        desc(mean_abs_shap)
      ) %>%
      mutate(
        shap_rank = row_number()
      )

    save_table(
      shap_importance,
      "05N_candidate_shap_importance.csv"
    )

    shap_importance_plot <- shap_importance %>%
      slice_head(
        n = top_n_features
      ) %>%
      mutate(
        display_label = paste0(
          feature_label,
          " [",
          feature_modality,
          "]"
        ),
        display_label = factor(
          display_label,
          levels = rev(display_label)
        )
      ) %>%
      ggplot(
        aes(
          x = display_label,
          y = mean_abs_shap,
          fill = feature_modality
        )
      ) +
      geom_col() +
      coord_flip() +
      labs(
        title = "SHAP feature importance",
        subtitle = paste0(
          "Interpretation-only full-cohort refit; ",
          shap_nsim,
          " Monte Carlo simulations"
        ),
        x = NULL,
        y = "Mean absolute SHAP value",
        fill = "Modality"
      ) +
      theme_minimal(base_size = 11)

    save_plot(
      shap_importance_plot,
      "05N_candidate_shap_importance.png",
      width = 10,
      height = 8
    )

    # SHAP beeswarm-style plot
    top_shap_features <- shap_importance %>%
      slice_head(
        n = min(
          20,
          nrow(shap_importance)
        )
      ) %>%
      pull(feature)

    shap_long <- shap_values %>%
      select(
        all_of(top_shap_features)
      ) %>%
      mutate(
        patient_index = row_number()
      ) %>%
      pivot_longer(
        cols = -patient_index,
        names_to = "feature",
        values_to = "shap_value"
      ) %>%
      left_join(
        shap_x %>%
          select(
            all_of(top_shap_features)
          ) %>%
          mutate(
            patient_index = row_number()
          ) %>%
          pivot_longer(
            cols = -patient_index,
            names_to = "feature",
            values_to = "feature_value"
          ),
        by = c(
          "patient_index",
          "feature"
        )
      ) %>%
      left_join(
        shap_importance %>%
          select(
            feature,
            shap_rank,
            feature_label
          ),
        by = "feature"
      ) %>%
      mutate(
        feature_label = factor(
          feature_label,
          levels = rev(
            shap_importance %>%
              filter(
                feature %in% top_shap_features
              ) %>%
              arrange(shap_rank) %>%
              pull(feature_label)
          )
        )
      )

    save_table(
      shap_long,
      "05N_candidate_shap_long_top_features.csv"
    )

    shap_beeswarm_plot <- ggplot(
      shap_long,
      aes(
        x = shap_value,
        y = feature_label,
        colour = feature_value
      )
    ) +
      geom_point(
        alpha = 0.65,
        position = position_jitter(
          height = 0.18,
          width = 0
        ),
        size = 1.6
      ) +
      geom_vline(
        xintercept = 0,
        linewidth = 0.4
      ) +
      labs(
        title = "SHAP summary of the lead candidate model",
        subtitle = paste0(
          "Positive SHAP values increase predicted MACE risk; ",
          "full-cohort interpretation refit"
        ),
        x = "SHAP contribution to predicted probability",
        y = NULL,
        colour = "Standardised\nfeature value"
      ) +
      theme_minimal(base_size = 10)

    save_plot(
      shap_beeswarm_plot,
      "05N_candidate_shap_summary_beeswarm.png",
      width = 10,
      height = 8
    )

    # Dependence plots for leading SHAP features
    dependence_features <- shap_importance %>%
      slice_head(
        n = min(
          top_n_shap_dependence,
          nrow(shap_importance)
        )
      ) %>%
      pull(feature)

    walk(
      dependence_features,
      function(current_feature) {
        dependence_data <- tibble(
          feature_value =
            shap_x[[current_feature]],
          shap_value =
            shap_values[[current_feature]]
        )

        dependence_plot <- ggplot(
          dependence_data,
          aes(
            x = feature_value,
            y = shap_value
          )
        ) +
          geom_point(
            alpha = 0.7
          ) +
          geom_smooth(
            method = "loess",
            se = TRUE
          ) +
          geom_hline(
            yintercept = 0,
            linetype = "dashed"
          ) +
          labs(
            title = paste0(
              "SHAP dependence: ",
              clean_feature_label(
                current_feature
              )
            ),
            subtitle = paste0(
              classify_feature_modality(
                current_feature
              ),
              " | interpretation-only full-cohort refit"
            ),
            x = "Standardised feature value",
            y = "SHAP contribution"
          ) +
          theme_minimal(base_size = 12)

        safe_feature_name <- current_feature %>%
          str_replace_all(
            "[^A-Za-z0-9]+",
            "_"
          )

        save_plot(
          dependence_plot,
          paste0(
            "05O_shap_dependence_",
            safe_feature_name,
            ".png"
          ),
          width = 7,
          height = 5
        )
      }
    )
  }
}

