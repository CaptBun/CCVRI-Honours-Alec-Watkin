  ,
  refit_candidate_features,
  drop = FALSE
]

refit_y <- processed_full$y_train
refit_weights <- make_weights(refit_y)

set.seed(123)

refit_cv <- cv.glmnet(
  x = refit_x,
  y = refit_y,
  family = "binomial",
  alpha = refit_alpha,
  weights = refit_weights,
  nfolds = 5,
  type.measure = "auc",
  maxit = 200000
)

refit_model <- glmnet(
  x = refit_x,
  y = refit_y,
  family = "binomial",
  alpha = refit_alpha,
  weights = refit_weights,
  lambda = refit_cv$lambda.min,
  maxit = 200000
)

